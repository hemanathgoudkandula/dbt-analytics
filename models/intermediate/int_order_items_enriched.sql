WITH I AS (SELECT * FROM {{ ref('stg_order_items') }}),
O AS (SELECT * FROM {{ ref('stg_orders') }}),
P AS (SELECT * FROM {{ ref('stg_products') }})
SELECT
  I.ORDER_ITEM_ID, I.ORDER_ID, O.CUSTOMER_ID, I.PRODUCT_ID,
  O.ORDER_DATE, O.ORDER_STATUS, I.QUANTITY, P.UNIT_PRICE,
  (I.QUANTITY*P.UNIT_PRICE)::NUMBER(18,2) AS GROSS_AMOUNT,
  CASE WHEN O.ORDER_STATUS='completed'
       THEN (I.QUANTITY*P.UNIT_PRICE)::NUMBER(18,2)
       ELSE 0::NUMBER(18,2) END AS NET_REVENUE
FROM I
INNER JOIN O ON I.ORDER_ID=O.ORDER_ID
INNER JOIN P ON I.PRODUCT_ID=P.PRODUCT_ID
